// The files other people read (`share/*`, `implement/pr.md`, the pull request body) carry no line that
// says a tool wrote them. An engine adds one by habit, a line under a pull request text that names it as
// the writer, so Nolzu takes such lines out after every run. Only a whole line that names a
// tool goes, with the blank line it leaves. Every other line stays exactly as it was.

// A tool by a name that means only the tool. A bare "cursor", "AI", "GPT" or "OpenAI" is a word a
// person's own text uses ("a cursor so long lists page fast", "the OpenAI SDK"), so those count only
// in a form that names the tool: "Cursor Agent", cursor.com, "OpenAI Codex", "an AI assistant".
const NAME = String.raw`(?:claude(?:\s+code)?|anthropic|(?:openai\s+)?codex|chatgpt|cursor(?:\s+agent|\.com)|gemini|(?:github\s+)?copilot|nolzu|an?\s+ai(?:\s+(?:assistant|agent|model|tool))?|ai\s+(?:assistant|agent|model|tool))(?![a-z0-9])`;
// The tool has to come right after the making verb, with only "the" and link or emphasis marks between,
// so "Built with the OpenAI SDK" stays. A sentence such as "This PR was generated by Claude Code" counts.
const MADE = new RegExp(
  String.raw`^(?:(?:this|the)\s+(?:pr|pull request|change|commit|summary|description|text|file|document|patch|code)\s+(?:was|is|has been)\s+)?(?:auto-?)?(?:generated|created|written|made|built|authored|drafted|prepared|produced)\s+(?:with|by|using|via)\s+(?:the\s+)?[[*_\x60]*${NAME}`,
  'i',
);
// A co-author trailer names its tool anywhere, often only in the address. Spelled with a class, so a
// plain text search for such lines does not stop on this one.
const CO_AUTHOR = /^co-authored[-]by:.*(?:claude|anthropic|codex|openai|chatgpt|cursor|gemini|copilot|nolzu)/i;
const NAMED = new RegExp(NAME, 'i');
const ROBOT = '\u{1F916}';
// Marks around a line that change nothing about what it says: a quote, emphasis, code ticks, a small
// html tag such as <sub>, and the robot.
const OPENING = /^(?:>\s*|<(?:sub|sup|small|em|i|b|strong|p|span)\b[^>]*>|[*_~\x60]+|\u{1F916}|\s+)+/iu;
const CLOSING = /(?:<\/[a-z]+>|[*_~\x60]+|\s+)+$/i;
const RULE = /^\s*(?:-{3,}|\*{3,}|_{3,})\s*$/;

export function isAttributionLine(line: string): boolean {
  const bare = line.replace(OPENING, '').replace(CLOSING, '');
  if (bare === '') return false;
  if (MADE.test(bare) || CO_AUTHOR.test(bare)) return true;
  // A robot line that names a tool anywhere.
  return line.replace(/^(?:>\s*|<[a-z]+[^>]*>|[*_~\x60]+|\s+)+/i, '').startsWith(ROBOT) && NAMED.test(bare);
}

// The text without its attribution lines. A removed line takes the blank line before it, or after it
// when it opened the text, so no gap is left behind. A rule (`---`) left last above a removed footer
// goes too. A text with none comes back unchanged.
export function withoutAttribution(text: string): string {
  const lines = text.split('\n');
  if (!lines.some(isAttributionLine)) return text;
  const kept: string[] = [];
  let dropBlank = false;
  let endedOnFooter = false;
  for (const line of lines) {
    if (isAttributionLine(line)) {
      if (kept.length > 0 && kept.at(-1)?.trim() === '') kept.pop();
      else if (kept.length === 0) dropBlank = true;
      endedOnFooter = true;
      continue;
    }
    if (dropBlank && line.trim() === '') continue;
    dropBlank = false;
    if (line.trim() !== '') endedOnFooter = false;
    kept.push(line);
  }
  if (endedOnFooter) {
    while (kept.length > 0 && kept.at(-1)?.trim() === '') kept.pop();
    if (RULE.test(kept.at(-1) ?? '')) kept.pop();
    while (kept.length > 0 && kept.at(-1)?.trim() === '') kept.pop();
  }
  // A text that ended on a newline still ends with one.
  const out = kept.join('\n');
  return text.endsWith('\n') && !out.endsWith('\n') ? `${out}\n` : out;
}
